import type { ShaderPaint } from '../types.ts'
import { multiPassFragmentShader, multiPassUniforms } from './multiPassFragment.ts'

export function exportPipelineReact(paint: Extract<ShaderPaint, { kind: 'multi-pass' }>): string {
  const style = {
    width: '100%',
    height: '100%',
    opacity: paint.composite?.opacity ?? 1,
    mixBlendMode: paint.composite?.blendMode ?? 'normal',
  }
  const uniforms = multiPassUniforms(paint)

  return `import { ShaderMount } from '@paper-design/shaders-react';

// Multi-Pass Shader Pipeline (${paint.pipeline?.name ?? 'Custom Material'})
// Generated by Paper (https://github.com/moslembabaee/paper)
const fragmentShader = \`${multiPassFragmentShader}\`;

const uniforms = ${JSON.stringify(uniforms, null, 2)};

export default function MaterialComposer() {
  return (
    <ShaderMount
      fragmentShader={fragmentShader}
      uniforms={uniforms}
      speed={${paint.animated ? paint.speed : 0}}
      frame={${paint.frame}}
      minPixelRatio={1}
      maxPixelCount={1500000}
      style={${JSON.stringify(style, null, 2)}}
    />
  );
}
`
}

export function exportPipelineGLSL(): string {
  return multiPassFragmentShader
}

export function exportPipelineUniforms(paint: Extract<ShaderPaint, { kind: 'multi-pass' }>): string {
  return JSON.stringify(multiPassUniforms(paint), null, 2)
}
