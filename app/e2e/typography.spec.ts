import { test, expect } from '@playwright/test'
import { waitForCanvasReady } from './helpers'

test('typography inspector updates axes and custom curves, supports undo and preset switching', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await waitForCanvasReady(page)
  await page.getByTestId('tool-text').click()
  const panel = page.getByTestId('inspector-panel')
  const text = page.locator('.scene-node.is-selected[data-element-type="text"]')
  await panel.getByRole('button', { name: 'Axes', exact: true }).click()
  await panel.getByLabel('Weight value', { exact: true }).fill('725')
  await panel.getByLabel('Width value', { exact: true }).fill('80')
  await expect(text.locator('.scene-text')).toHaveCSS('font-variation-settings', /"wdth" 80.*"wght" 725|"wght" 725.*"wdth" 80/)
  await page.getByTestId('history-undo').click()
  await expect(panel.getByLabel('Width value', { exact: true })).toHaveValue('100')
  await panel.getByRole('button', { name: 'Path', exact: true }).click()
  await panel.getByRole('switch', { name: 'Toggle text-on-path deformation' }).click()
  await expect(text.locator('textPath')).toHaveCount(1)
  await panel.getByRole('button', { name: 'Custom', exact: true }).click()
  const custom = panel.getByLabel('Custom text path data')
  await custom.fill('M 0 30 C 60 0 160 90 240 30')
  await custom.press('Tab')
  await expect(text.locator('defs path')).toHaveAttribute('d', 'M 0 30 C 60 0 160 90 240 30')
  await panel.getByRole('button', { name: 'Center Align', exact: true }).click()
  await expect(text.locator('textPath')).toHaveAttribute('startOffset', '50%')
  await panel.getByRole('button', { name: 'Arc', exact: true }).click()
  await expect(text.locator('defs path')).toHaveAttribute('d', / Q /)
  await panel.getByRole('button', { name: 'Reverse', exact: true }).click()
  await expect(text.locator('defs path')).toHaveAttribute('d', / C /)
  await expect(text.locator('.scene-text-path-guide')).toHaveCount(1)
  await page.getByTestId('dev-mode-toggle').click()
  await expect(page.getByTestId('dev-mode-panel')).toContainText('font-variation-settings')
  expect(errors).toEqual([])
})

test('linked text follows live vector geometry edits', async ({ page }) => {
  await waitForCanvasReady(page)
  await page.getByTestId('tool-text').click()
  const panel = page.getByTestId('inspector-panel')
  const text = page.locator('.scene-node.is-selected[data-element-type="text"]')
  const textId = await text.getAttribute('data-element-id')
  await panel.getByRole('button', { name: 'Path', exact: true }).click()
  await panel.getByRole('switch', { name: 'Toggle text-on-path deformation' }).click()
  const select = panel.getByLabel('Target canvas vector path')
  const targetId = await select.locator('option').nth(1).getAttribute('value')
  await select.selectOption(targetId!)
  const curve = page.locator(`[data-element-id="${textId}"] .scene-text-on-path defs path`)
  const before = await curve.getAttribute('d')
  await page.locator(`[data-layer-id="${targetId}"] .layer-select`).click()
  await panel.getByLabel('SVG path data', { exact: true }).fill('M 0 0 C 5 15 10 5 16 16')
  await panel.getByLabel('SVG path data', { exact: true }).press('Tab')
  await expect(curve).not.toHaveAttribute('d', before!)
  await page.getByTestId('history-undo').click()
  await expect(curve).toHaveAttribute('d', before!)
})
