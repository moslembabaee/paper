import { test, expect } from '@playwright/test'
import { waitForCanvasReady } from './helpers'

test('frame controls reflow children, resize fill, undo spacing and retain layout after reload', async ({ page }) => {
  await waitForCanvasReady(page)
  await page.getByTestId('tool-frame').click()
  const frame = page.locator('.scene-frame.is-selected')
  const frameId = await frame.getAttribute('data-element-id')
  const inspector = page.getByTestId('inspector-panel')
  const editNumber = async (name: string, value: string) => {
    const field = inspector.getByRole('spinbutton', { name, exact: true })
    await field.fill(value)
    await field.press('Enter')
  }
  await inspector.getByRole('button', { name: 'Add auto layout' }).click()
  await editNumber('Width', '400')
  await editNumber('Height', '240')
  await editNumber('Padding top', '10')
  await editNumber('Padding right', '20')
  await editNumber('Padding bottom', '30')
  await editNumber('Padding left', '40')
  await editNumber('Gap', '12')
  await page.getByTestId('tool-rectangle').click()
  const first = page.locator('.scene-node.is-selected')
  const firstId = await first.getAttribute('data-element-id')
  await inspector.getByRole('combobox', { name: 'Width sizing', exact: true }).selectOption('fill')
  await inspector.getByRole('combobox', { name: 'Height sizing', exact: true }).selectOption('fill')
  await expect(first).toHaveCSS('left', '40px')
  await expect(first).toHaveCSS('top', '10px')
  await expect(first).toHaveCSS('width', '340px')
  await expect(first).toHaveCSS('height', '200px')
  await expect(inspector.getByRole('spinbutton', { name: 'X', exact: true })).toBeDisabled()
  await page.getByTestId('tool-rectangle').click()
  const secondId = await page.locator('.scene-node.is-selected').getAttribute('data-element-id')
  const firstNode = page.locator(`[data-element-id="${firstId}"]`)
  const secondNode = page.locator(`[data-element-id="${secondId}"]`)
  await expect(firstNode).toHaveCSS('width', '208px')
  await expect(secondNode).toHaveCSS('left', '260px')
  await page.getByTestId('layer-tree').getByRole('button', { name: 'Frame', exact: true }).click()
  await inspector.getByRole('button', { name: 'Vertical', exact: true }).click()
  await expect(secondNode).toHaveCSS('top', '90px')
  await page.getByTestId('layer-tree').getByRole('button', { name: 'Expand Frame', exact: true }).click()
  await page.getByTestId('layer-tree').getByRole('button', { name: 'Rectangle', exact: true }).last().click()
  await inspector.getByRole('combobox', { name: 'Height sizing', exact: true }).selectOption('fixed')
  await page.getByTestId('layer-tree').getByRole('button', { name: 'Frame', exact: true }).click()
  await editNumber('Gap', '24')
  await expect(secondNode).toHaveCSS('top', '102px')
  await page.getByTestId('history-undo').click()
  await expect(inspector.getByRole('spinbutton', { name: 'Gap', exact: true })).toHaveValue('12')
  await editNumber('Width', '500')
  await expect(firstNode).toHaveCSS('width', '440px')
  await expect(page.locator('.local-status')).toHaveText('Saved locally')
  await page.reload()
  await expect(page.locator(`[data-element-id="${frameId}"]`)).toHaveCSS('width', '500px')
  await expect(firstNode).toHaveCSS('width', '440px')
  await expect(secondNode).toHaveCSS('top', '90px')
})
